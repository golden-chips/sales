#!/usr/bin/env bash
# GOLDEN ERP — one-command installation on a fresh Linux server (Ubuntu/Debian) with Docker.
#   ./setup.sh                 → http://SERVER-IP            (trial)
#   DOMAIN=erp.example.ly ./setup.sh  → https://erp.example.ly  (automatic certificate)
#   SEED_DEMO=false ./setup.sh → no DEMO company (production)
set -euo pipefail
cd "$(dirname "$0")"
command -v docker >/dev/null || { echo "Docker is required: curl -fsSL https://get.docker.com | sh"; exit 1; }
rnd() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }

if [ ! -f .env ]; then
  DOMAIN="${DOMAIN:-}"
  if [ -n "$DOMAIN" ]; then PUBLIC_URL="https://$DOMAIN"; HTTP_PORT="127.0.0.1:8080"
  else IP="$(hostname -I 2>/dev/null | awk '{print $1}')"; PUBLIC_URL="http://${IP:-localhost}"; HTTP_PORT="80"; fi
  umask 077
  cat > .env <<ENV
# generated by setup.sh on $(date -u +%F) — keep this file secret and backed up
DOMAIN=$DOMAIN
PUBLIC_URL=$PUBLIC_URL
HTTP_PORT=$HTTP_PORT
OWNER_DB_PASSWORD=$(rnd 32)
APP_DB_PASSWORD=$(rnd 32)
JWT_SECRET=$(rnd 64)
PLATFORM_JWT_SECRET=$(rnd 64)
SEED_DEMO=${SEED_DEMO:-true}
ENV
  echo "created deploy/.env with random secrets"
fi
set -a; . ./.env; set +a

PROFILE=""; [ -n "${DOMAIN:-}" ] && PROFILE="--profile https"
BUILD="--build"; [ -n "${SKIP_BUILD:-}" ] && BUILD="--no-build"   # SKIP_BUILD=1: use images built beforehand
docker compose $PROFILE up -d $BUILD

echo "waiting for the API…"
for i in $(seq 1 90); do
  if docker compose exec -T api wget -qO- http://127.0.0.1:4000/health >/dev/null 2>&1; then break; fi
  sleep 2
  [ "$i" = 90 ] && { docker compose logs --tail 50 api; echo "API did not start"; exit 1; }
done

# first accounts — created once; passwords are printed ONLY now
if [ ! -f .accounts-created ]; then
  ADMIN_PW="Adm!$(rnd 14)"; OWNER_PW="Own!$(rnd 14)"; DEMO_PW="Demo!$(rnd 12)"; REP_PW="Rep!$(rnd 12)"
  docker compose exec -T \
    -e PLATFORM_ADMIN_EMAIL="${PLATFORM_ADMIN_EMAIL:-admin@golden-erp.local}" -e PLATFORM_ADMIN_PASSWORD="$ADMIN_PW" \
    -e GOLDEN_OWNER_EMAIL="${GOLDEN_OWNER_EMAIL:-owner@goldenchips.local}" -e GOLDEN_OWNER_PASSWORD="$OWNER_PW" \
    -e DEMO_OWNER_PASSWORD="$DEMO_PW" -e DEMO_REP_PASSWORD="$REP_PW" -e SEED_DEMO="${SEED_DEMO:-true}" \
    api ./node_modules/.bin/tsx scripts/seed.ts
  touch .accounts-created
  cat <<MSG

==================================================================
 GOLDEN ERP is running at: $PUBLIC_URL
 Save these passwords now (they are not stored anywhere else):
   Platform admin : ${PLATFORM_ADMIN_EMAIL:-admin@golden-erp.local} / $ADMIN_PW   ($PUBLIC_URL/platform)
   Golden Chips   : company code golden-chips · ${GOLDEN_OWNER_EMAIL:-owner@goldenchips.local} / $OWNER_PW
MSG
  [ "${SEED_DEMO:-true}" != "false" ] && echo "   DEMO company   : company code demo-foods · owner@demo-foods.example / $DEMO_PW · rep@demo-foods.example / $REP_PW"
  echo "=================================================================="
else
  echo "GOLDEN ERP updated and running at: $PUBLIC_URL"
fi
